// Generates the five non-English page-content dictionaries from the English
// source (src/i18n/pages/en.ts) as English-valued stubs that `satisfies
// PageContent`. Run after editing en.ts to keep the locale files structurally
// in sync (typecheck-green); the final translation pass then edits values in
// place. Idempotent — safe to re-run.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const pagesDir = join(here, "..", "src", "i18n", "pages");
const LOCALES = ["ar", "fr", "de", "es", "it"];

const en = await readFile(join(pagesDir, "en.ts"), "utf8");

// Extract the object body: from `export const enPages = {` through its matching
// closing `} ;` line immediately preceding the `export type` line.
const startMarker = "export const enPages = {";
const endMarker = "\n} ;\n\nexport type PageContent = typeof enPages;";
const startIdx = en.indexOf(startMarker);
const endIdx = en.indexOf(endMarker);
if (startIdx === -1 || endIdx === -1) {
  throw new Error("gen-page-stubs: could not locate enPages object markers in en.ts — did its shape change?");
}
const body = en.slice(startIdx + startMarker.length, endIdx); // between `{` and `}`
// Drop the `// APPEND_MARKER` helper line so it can't comment out the closing brace.
const cleanBody = body.replace(/[ \t]*\/\/ APPEND_MARKER[ \t]*\n?/, "");

for (const loc of LOCALES) {
  const out = `/**
 * ${loc.toUpperCase()} page-content dictionary (Phase 3 i18n, Track C).
 * Auto-generated from en.ts as an English-valued stub — TRANSLATE the string
 * VALUES in place into ${loc}. Keep every key, every array length and every
 * placeholder ({count}, {name}, …) and the brand "Ptah Tours" verbatim.
 * Regenerated by scripts/gen-page-stubs.mjs; re-running OVERWRITES this file,
 * so translate only after en.ts is final.
 */
import type { PageContent } from "./en";

export const ${loc}Pages = {${cleanBody}} satisfies PageContent;
`;
  await writeFile(join(pagesDir, `${loc}.ts`), out, "utf8");
  console.log(`wrote src/i18n/pages/${loc}.ts`);
}
