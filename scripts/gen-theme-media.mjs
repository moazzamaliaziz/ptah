// One-off codegen: merge scripts/theme-images.out.json (src/width/height/slug per
// converted WebP) with each set's manifest.json (title/creator/license/page) into
// the typed, committed data module src/content/theme-media.ts.
// Alt/caption use the manifest's own subject/title (source-grounded, never invented).
// Run after convert-theme-images.mjs: `node scripts/gen-theme-media.mjs`.
import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const SRC_ROOT = "C:/Users/Moazzam Ali/Downloads/images/_work";
const THEMES = {
  heritage: "egypt-heritage-images",
  "the-nile": "the-nile-images",
  deserts: "deserts-sinai-images",
  "red-sea": "red-sea-images",
  "when-to-visit": "when-to-visit-images",
};

const slugOf = (file) => file.replace(/^\d{2}-/, "").replace(/\.jpe?g$/i, "");

const converted = JSON.parse(
  await readFile(resolve(process.cwd(), "scripts/theme-images.out.json"), "utf8"),
);

const manifests = {};
for (const [theme, folder] of Object.entries(THEMES)) {
  manifests[theme] = JSON.parse(await readFile(join(SRC_ROOT, folder, "manifest.json"), "utf8"));
}

const grouped = {};
for (const theme of Object.keys(THEMES)) grouped[theme] = [];

for (const row of converted) {
  const man = manifests[row.theme].find((m) => slugOf(m.file) === row.slug);
  if (!man) throw new Error(`No manifest entry for ${row.theme}/${row.slug}`);
  grouped[row.theme].push({
    slug: row.slug,
    src: row.src,
    width: row.width,
    height: row.height,
    alt: man.subject || man.title,
    caption: man.subject || man.title,
    credit: {
      title: man.title,
      creator: man.creator,
      license: man.license,
      page: man.page,
    },
  });
}

const header = `/**
 * Curated theme photography for the five editorial pages (heritage / the-nile /
 * deserts / red-sea / when-to-visit) plus their on-page attribution.
 *
 * GENERATED by scripts/gen-theme-media.mjs from the Wikimedia Commons image sets
 * (scripts/convert-theme-images.mjs emits the WebP + dimensions; each set ships a
 * manifest.json with the required creator/license/source-page metadata). Do not
 * hand-edit — re-run the generator instead.
 *
 * Every image is CC-licensed or public-domain; on-page credit (creator + license
 * + Commons link) is REQUIRED and rendered by <ImageCredits>. alt/caption come
 * verbatim from each file's manifest subject/title — descriptive, never invented.
 * These English strings are shared across all locales for now (English-first);
 * lift into the i18n dictionaries when the pages are translated.
 */

export type ThemeSlug = "heritage" | "the-nile" | "deserts" | "red-sea" | "when-to-visit";

export interface ImageCredit {
  /** Title of the source work on Wikimedia Commons. */
  title: string;
  /** Attributed author/creator string, verbatim from the manifest. */
  creator: string;
  /** License short name, e.g. "CC BY 4.0", "Public domain", "CC0". */
  license: string;
  /** Canonical Commons file page (attribution target). */
  page: string;
}

export interface ThemeImage {
  /** Stable id within a theme, e.g. "giza-pyramids". */
  slug: string;
  /** Path under /public — optimized WebP. */
  src: string;
  /** Intrinsic pixel dimensions of the WebP (for next/image + masonry). */
  width: number;
  height: number;
  /** Descriptive English alt text (from manifest subject). */
  alt: string;
  /** Short English caption for gallery/credit rows. */
  caption: string;
  credit: ImageCredit;
}

`;

const body =
  `export const themeMedia: Record<ThemeSlug, ThemeImage[]> = ${JSON.stringify(grouped, null, 2)};\n\n` +
  `/** Look up one image in a theme by slug (feature rows / spot placements). */\n` +
  `export function themeImage(theme: ThemeSlug, slug: string): ThemeImage {\n` +
  `  const found = themeMedia[theme].find((i) => i.slug === slug);\n` +
  `  if (!found) throw new Error(\`Unknown theme image: \${theme}/\${slug}\`);\n` +
  `  return found;\n` +
  `}\n`;

await writeFile(resolve(process.cwd(), "src/content/theme-media.ts"), header + body);
const total = Object.values(grouped).reduce((n, a) => n + a.length, 0);
console.log(`Wrote src/content/theme-media.ts (${total} images).`);
